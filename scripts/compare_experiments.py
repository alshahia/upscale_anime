#!/usr/bin/env python
"""
Experiment comparison tool for analyzing different training runs.
Compares metrics, training curves, and model performance.
"""
import argparse
import json
from pathlib import Path
from typing import Dict, List
import matplotlib.pyplot as plt
import numpy as np


def load_experiment_results(exp_dir: Path) -> Dict:
    """Load results from experiment directory."""
    results = {}
    
    # Try to load pipeline results
    pipeline_file = exp_dir / 'results' / 'pipeline_results.json'
    if pipeline_file.exists():
        with open(pipeline_file) as f:
            results['pipeline'] = json.load(f)
    
    # Try to load benchmark results
    benchmark_file = exp_dir / 'results' / 'benchmark.json'
    if benchmark_file.exists():
        with open(benchmark_file) as f:
            results['benchmark'] = json.load(f)
    
    # Try to load training logs
    log_file = exp_dir / 'logs' / 'training_log.json'
    if log_file.exists():
        with open(log_file) as f:
            results['training_log'] = json.load(f)
    
    return results


def compare_benchmarks(experiments: Dict[str, Dict]) -> None:
    """Compare benchmark results across experiments."""
    print("\n" + "="*80)
    print("BENCHMARK COMPARISON")
    print("="*80)
    
    # Collect metrics
    metrics = ['psnr', 'ssim', 'lpips', 'dists']
    data = {m: [] for m in metrics}
    labels = []
    
    for name, exp in experiments.items():
        if 'benchmark' in exp and 'average' in exp['benchmark']:
            avg = exp['benchmark']['average']
            labels.append(name)
            for m in metrics:
                data[m].append(avg.get(m, 0))
    
    if not labels:
        print("No benchmark data found!")
        return
    
    # Print table
    print(f"\n{'Experiment':<30} {'PSNR':>10} {'SSIM':>10} {'LPIPS':>10} {'DISTS':>10}")
    print("-"*80)
    for i, label in enumerate(labels):
        print(f"{label:<30} {data['psnr'][i]:>10.2f} {data['ssim'][i]:>10.4f} "
              f"{data['lpips'][i]:>10.4f} {data['dists'][i]:>10.4f}")
    
    # Create visualization
    fig, axes = plt.subplots(2, 2, figsize=(12, 10))
    axes = axes.flatten()
    
    for idx, metric in enumerate(metrics):
        ax = axes[idx]
        x = np.arange(len(labels))
        bars = ax.bar(x, data[metric])
        ax.set_xticks(x)
        ax.set_xticklabels(labels, rotation=45, ha='right')
        ax.set_ylabel(metric.upper())
        ax.set_title(f'{metric.upper()} Comparison')
        ax.grid(axis='y', alpha=0.3)
        
        # Color best result
        if metric in ['psnr', 'ssim']:  # Higher is better
            best_idx = np.argmax(data[metric])
        else:  # Lower is better
            best_idx = np.argmin(data[metric])
        bars[best_idx].set_color('green')
    
    plt.tight_layout()
    plt.savefig('experiment_comparison.png', dpi=150, bbox_inches='tight')
    print(f"\n[CHART] Comparison chart saved: experiment_comparison.png")


def compare_training_curves(experiments: Dict[str, Dict]) -> None:
    """Compare training curves across experiments."""
    print("\n" + "="*80)
    print("TRAINING CURVE COMPARISON")
    print("="*80)
    
    fig, axes = plt.subplots(1, 2, figsize=(14, 5))
    
    for name, exp in experiments.items():
        if 'training_log' not in exp:
            continue
        
        log = exp['training_log']
        epochs = log.get('epochs', [])
        losses = log.get('losses', [])
        val_losses = log.get('val_losses', [])
        
        if epochs and losses:
            axes[0].plot(epochs, losses, label=name, alpha=0.8)
        
        if epochs and val_losses:
            axes[1].plot(epochs, val_losses, label=name, alpha=0.8)
    
    axes[0].set_xlabel('Epoch')
    axes[0].set_ylabel('Training Loss')
    axes[0].set_title('Training Loss Curves')
    axes[0].legend()
    axes[0].grid(alpha=0.3)
    
    axes[1].set_xlabel('Epoch')
    axes[1].set_ylabel('Validation Loss')
    axes[1].set_title('Validation Loss Curves')
    axes[1].legend()
    axes[1].grid(alpha=0.3)
    
    plt.tight_layout()
    plt.savefig('training_curves_comparison.png', dpi=150, bbox_inches='tight')
    print(f"[UP] Training curves saved: training_curves_comparison.png")


def generate_summary_report(experiments: Dict[str, Dict], output_file: str):
    """Generate a detailed comparison report."""
    report = []
    
    report.append("# Experiment Comparison Report\n")
    report.append("Generated by: compare_experiments.py\n\n")
    
    # Summary table
    report.append("## Summary Table\n\n")
    report.append("| Experiment | PSNR | SSIM | LPIPS | Epochs | Training Time |\n")
    report.append("|------------|------|------|-------|--------|---------------|\n")
    
    for name, exp in experiments.items():
        psnr = ssim = lpips = epochs = time = "N/A"
        
        if 'benchmark' in exp and 'average' in exp['benchmark']:
            avg = exp['benchmark']['average']
            psnr = f"{avg.get('psnr', 0):.2f}"
            ssim = f"{avg.get('ssim', 0):.4f}"
            lpips = f"{avg.get('lpips', 0):.4f}"
        
        if 'pipeline' in exp:
            pipe = exp['pipeline']
            elapsed = pipe.get('elapsed_time', 0)
            hours = int(elapsed // 3600)
            minutes = int((elapsed % 3600) // 60)
            time = f"{hours}h {minutes}m"
            epochs = str(pipe.get('completed_steps', 'N/A'))
        
        report.append(f"| {name} | {psnr} | {ssim} | {lpips} | {epochs} | {time} |\n")
    
    report.append("\n## Key Findings\n\n")
    
    # Find best model
    best_psnr = 0
    best_model = None
    for name, exp in experiments.items():
        if 'benchmark' in exp and 'average' in exp['benchmark']:
            psnr = exp['benchmark']['average'].get('psnr', 0)
            if psnr > best_psnr:
                best_psnr = psnr
                best_model = name
    
    if best_model:
        report.append(f"- **Best PSNR:** {best_model} with {best_psnr:.2f} dB\n")
    
    # Write report
    with open(output_file, 'w') as f:
        f.writelines(report)
    
    print(f"📄 Report saved: {output_file}")


def main():
    parser = argparse.ArgumentParser(description='Compare training experiments')
    parser.add_argument('--experiments', type=str, required=True,
                       help='Comma-separated list of experiment directories')
    parser.add_argument('--output', type=str, default='experiment_comparison.md',
                       help='Output report file')
    parser.add_argument('--visualize', action='store_true',
                       help='Create visualization charts')
    
    args = parser.parse_args()
    
    # Load experiments
    exp_names = args.experiments.split(',')
    experiments = {}
    
    print("Loading experiments...")
    for name in exp_names:
        exp_dir = Path(name.strip())
        if not exp_dir.exists():
            print(f"[WARN]  Warning: Directory not found: {exp_dir}")
            continue
        
        print(f"  Loading: {exp_dir}")
        experiments[exp_dir.name] = load_experiment_results(exp_dir)
    
    if not experiments:
        print("[ERROR] No experiments loaded!")
        return
    
    print(f"\n[OK] Loaded {len(experiments)} experiments")
    
    # Compare
    compare_benchmarks(experiments)
    
    if args.visualize:
        compare_training_curves(experiments)
    
    # Generate report
    generate_summary_report(experiments, args.output)
    
    print("\n[OK] Comparison complete!")


if __name__ == '__main__':
    main()
